#!/usr/bin/env python3
"""derives platform/shaders/raster.frag, the GX2 build of Zakuro's fragment
ubershader, from zakuro/crates/zakuro-gpu/shaders/raster.frag. run it again
when the upstream shader changes:

    python3 tools/gx2_raster_frag.py

what changes for CafeGLSL, the offline GX2 compiler:
- specialization constants become plain constants, with DYNAMIC on so the
  combiners are read from the Draw block. LIGHTING and the procedural
  texture's switch (TEXTURE_CONFIG & 0x400) stay compile-time choices,
  ZW_LIGHTING and ZW_TEXTURE_CONFIG, one compiled variant each.
- no descriptor sets.
- the Tables storage buffer becomes a uniform block of vec4s holding the
  same bytes, two vec2 entries each, read through table_entry().
- precise comes off function return types, which Mesa rejects.
- the w-buffer reads 1/w from a varying instead of gl_FragCoord.w.
"""
import re
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
source = root / "zakuro/crates/zakuro-gpu/shaders/raster.frag"
target = root / "platform/shaders/raster.frag"

text = source.read_text()

def constant(match):
    name = match.group(1)
    value = {"DYNAMIC": "1u", "LIGHTING": "ZW_LIGHTING", "TEXTURE_CONFIG": "ZW_TEXTURE_CONFIG"}.get(name, "0u")
    return f"const uint {name} = {value};"

text, count = re.subn(r"layout\(constant_id = \d+\) const uint (\w+) = 0u;", constant, text)
assert count == 30, f"expected 30 specialization constants, found {count}"
text, count = re.subn(r"layout\(set = 0, binding = (\d+)\)", r"layout(binding = \1)", text)
text, count2 = re.subn(r"layout\(std140, set = 0, binding = (\d+)\)", r"layout(std140, binding = \1)", text)
assert count + count2 >= 4, "the descriptor bindings changed"

block = re.compile(r"layout\(std430, set = 0, binding = (\d+)\) readonly buffer Tables \{.*?vec2 tables\[\];\n\};", re.S)
match = block.search(text)
assert match, "the Tables buffer changed"
entries = 24 * 256 + 3 * 128 + 2 * 256 + 2 * 256 + 128
replacement = f"""// the tables, {entries} vec2 entries, two to a vec4: GX2 has no storage
// buffers. the same bytes the Vulkan backend's buffer holds
layout(std140, binding = {match.group(1)}) uniform Tables {{
    vec4 table_words[{entries // 2}];
}};

vec2 table_entry(uint index) {{
    vec4 words = table_words[index >> 1u];
    return (index & 1u) != 0u ? words.zw : words.xy;
}}"""
text = text[: match.start()] + replacement + text[match.end() :]

# tables[expression] -> table_entry(expression), brackets matched
out = []
i = 0
needle = "tables["
while True:
    j = text.find(needle, i)
    if j < 0:
        out.append(text[i:])
        break
    if j > 0 and (text[j - 1].isalnum() or text[j - 1] == "_"):
        out.append(text[i : j + len(needle)])
        i = j + len(needle)
        continue
    out.append(text[i:j])
    depth = 1
    k = j + len(needle)
    while depth:
        if text[k] == "[":
            depth += 1
        elif text[k] == "]":
            depth -= 1
        k += 1
    out.append("table_entry(" + text[j + len(needle) : k - 1] + ")")
    i = k
text = "".join(out)
assert "tables[" not in text

# gl_FragCoord.w is 1/w in GLSL, but Latte's position input carries w itself,
# and whether the compiler turns it over is unverified: take 1/w from the
# vertex shader instead, interpolated linearly on the screen as it is
anchor = "layout(location = 5) in vec4 in_view;"
assert text.count(anchor) == 1, "the inputs changed"
text = text.replace(anchor, anchor + "\n// 1/w, what GLSL gives as the w of gl_FragCoord, from raster.vert\nlayout(location = 6) noperspective in float zw_inv_w;")
text = text.replace("gl_FragCoord.w", "zw_inv_w")

# Mesa, which CafeGLSL is built on, takes precise on variables but not on a
# function's return type, which glslang allows: the functions' bodies keep
# their precise variables
text, count = re.subn(r"^precise (\w+ \w+\()", r"\1", text, flags=re.M)
assert count > 0, "no precise functions left, check whether this is still needed"

lines = text.split("\n")
assert lines[0].startswith("#version")
header = [
    lines[0],
    "",
    "// GENERATED by tools/gx2_raster_frag.py from Zakuro's shaders/raster.frag,",
    "// for GX2. don't edit; change the generator or the original.",
    "#ifndef ZW_LIGHTING",
    "#define ZW_LIGHTING 0u",
    "#endif",
    "#ifndef ZW_TEXTURE_CONFIG",
    "#define ZW_TEXTURE_CONFIG 0u",
    "#endif",
]
target.write_text("\n".join(header + lines[1:]))
print(f"wrote {target.relative_to(root)}")
