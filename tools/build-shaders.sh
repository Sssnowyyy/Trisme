#!/usr/bin/env bash
# compiles the GX2 rasterizer's shaders (platform/shaders/) ahead of time
# with CafeGLSL's glslcompiler and turns them into one object for the kit:
#
#     tools/build-shaders.sh <output.o>
#
# the compiler is looked for in $CAFEGLSL (the glslcompiler binary itself),
# $CAFEGLSL_DIR/bin, PATH and $DEVKITPRO/tools/bin. get it from
# https://github.com/Exzap/CafeGLSL/releases (the build for your computer,
# not the wiiu-ppc one). without it the object holds no shaders, which is
# fine: games then draw their 3D on the CPU. ZW_REQUIRE_GX2=1 makes a missing
# compiler or a failed compile an error instead.
#
# works in bash on Linux and macOS and in devkitPro's MSYS2 on Windows.
set -euo pipefail

if [ $# -ne 1 ]; then
  echo "usage: $0 <output.o>" >&2
  exit 2
fi
output="$1"
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
shaders="$root/platform/shaders"
export DEVKITPRO="${DEVKITPRO:-/opt/devkitpro}"
export DEVKITPPC="${DEVKITPPC:-$DEVKITPRO/devkitPPC}"
export PATH="$DEVKITPPC/bin:$DEVKITPRO/tools/bin:$PATH"

# glslcompiler and powerpc-eabi-gcc are native programs on Windows: hand
# them C:/... paths there
case "$(uname -s)" in
  MINGW* | MSYS* | CYGWIN*) native() { cygpath -m "$1"; } ;;
  *) native() { printf '%s\n' "$1"; } ;;
esac

work="$(mktemp -d "${TMPDIR:-/tmp}/zakuro-shaders.XXXXXX")"
trap 'rm -rf "$work"' EXIT

find_compiler() {
  if [ -n "${CAFEGLSL:-}" ]; then
    echo "$CAFEGLSL"
    return
  fi
  local candidate
  for candidate in "${CAFEGLSL_DIR:-}/bin/glslcompiler" "${CAFEGLSL_DIR:-}/bin/glslcompiler.exe"; do
    if [ -n "${CAFEGLSL_DIR:-}" ] && [ -x "$candidate" ]; then
      echo "$candidate"
      return
    fi
  done
  command -v glslcompiler 2>/dev/null || command -v glslcompiler.exe 2>/dev/null || true
}

# the shaders, in the order platform/gx2.c reads them: raster variants 0-7
# (bit 0 lighting, bit 1 the procedural texture, bit 2 writes depth, as
# ZW_GX2_SHADER_*), then depth_load, then depth_store
names=()
compiled=0
compiler="$(find_compiler)"
fail() {
  if [ "${ZW_REQUIRE_GX2:-0}" = 1 ]; then
    echo "error: $1" >&2
    exit 1
  fi
  echo "warning: $1; building without GX2 shaders, games will draw on the CPU" >&2
  names=()
  compiled=0
}

compile_pair() { # name vertex pixel
  local log="$work/$1.log"
  if ! "$compiler" --uniform-mode block -vs "$(native "$2")" -ps "$(native "$3")" -o "$(native "$work/$1.gsh")" >"$log" 2>&1; then
    cat "$log" >&2
    return 1
  fi
  names+=("$1")
}

if [ -z "$compiler" ]; then
  fail "CafeGLSL's glslcompiler not found (set CAFEGLSL or CAFEGLSL_DIR)"
else
  echo "compiling GX2 shaders with $compiler"
  compiled=1
  for variant in 0 1 2 3 4 5 6 7; do
    source="$work/raster_$variant.frag"
    {
      head -n 1 "$shaders/raster.frag"
      if [ $((variant & 1)) -ne 0 ]; then echo "#define ZW_LIGHTING 1u"; fi
      if [ $((variant & 2)) -ne 0 ]; then echo "#define ZW_TEXTURE_CONFIG 0x400u"; fi
      if [ $((variant & 4)) -ne 0 ]; then echo "#define WRITES_DEPTH 1"; fi
      tail -n +2 "$shaders/raster.frag"
    } >"$source"
    if ! compile_pair "raster_$variant" "$shaders/raster.vert" "$source"; then
      fail "raster.frag variant $variant didn't compile"
      break
    fi
  done
  if [ "$compiled" = 1 ]; then
    compile_pair depth_load "$shaders/fullscreen.vert" "$shaders/depth_load.frag" \
      && compile_pair depth_store "$shaders/fullscreen.vert" "$shaders/depth_store.frag" \
      || fail "the depth shaders didn't compile"
  fi
fi

c="$work/gx2_shaders.c"
{
  echo "/* generated by tools/build-shaders.sh: the GX2 shaders as .gsh files */"
  echo "#include <stdint.h>"
  echo "typedef struct ZwGx2ShaderBlob { const uint8_t *data; uint32_t size; } ZwGx2ShaderBlob;"
  if [ "${#names[@]}" -eq 0 ]; then
    echo "const ZwGx2ShaderBlob zw_gx2_shader_blobs[1] = {{0, 0}};"
    echo "const uint32_t zw_gx2_shader_count = 0;"
  else
    for name in "${names[@]}"; do
      echo "static const uint8_t ${name}_gsh[] __attribute__((aligned(256))) = {"
      od -An -v -tx1 "$work/$name.gsh" | sed -e 's/ *\([0-9a-f][0-9a-f]\)/0x\1,/g'
      echo "};"
    done
    echo "const ZwGx2ShaderBlob zw_gx2_shader_blobs[] = {"
    for name in "${names[@]}"; do
      echo "    {${name}_gsh, sizeof ${name}_gsh},"
    done
    echo "};"
    echo "const uint32_t zw_gx2_shader_count = ${#names[@]};"
  fi
} >"$c"

powerpc-eabi-gcc -O2 -mcpu=750 -meabi -mhard-float -c "$(native "$c")" -o "$(native "$output")"
echo "GX2 shaders: ${#names[@]} in $output"
